#!/bin/bash
set -euo pipefail
PROJECT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
cd "$PROJECT_DIR"
export CLANG_MODULE_CACHE_PATH="$PROJECT_DIR/.build/module-cache"
export SWIFTPM_MODULECACHE_OVERRIDE="$CLANG_MODULE_CACHE_PATH"
mkdir -p "$CLANG_MODULE_CACHE_PATH"
CONFIGURATION="${1:-release}"
swift build --disable-sandbox -c "$CONFIGURATION"
BIN_DIR="$(swift build --disable-sandbox -c "$CONFIGURATION" --show-bin-path)"
APP_DIR="$PROJECT_DIR/dist/OvO.app"
mkdir -p "$APP_DIR/Contents/MacOS" "$APP_DIR/Contents/Resources"
cp "$BIN_DIR/Ovo" "$APP_DIR/Contents/MacOS/Ovo"
cp "$PROJECT_DIR/Resources/Info.plist" "$APP_DIR/Contents/Info.plist"
cp "$PROJECT_DIR/Resources/DeepSeek.png" "$APP_DIR/Contents/Resources/DeepSeek.png"
swift "$PROJECT_DIR/scripts/make-icon.swift" "$PROJECT_DIR/Resources/AppIcon.png" "$PROJECT_DIR/.build/Ovo.iconset"
iconutil -c icns "$PROJECT_DIR/.build/Ovo.iconset" -o "$APP_DIR/Contents/Resources/Ovo.icns"
python3 "$PROJECT_DIR/scripts/sign-app.py" "$APP_DIR"
codesign --verify --deep --strict "$APP_DIR"
printf '\nBuilt: %s\n' "$APP_DIR"
